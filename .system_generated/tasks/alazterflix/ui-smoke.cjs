const fs = require('fs')
const path = require('path')
const esbuild = require('esbuild')
const sass = require('sass')
const { _electron, expect } = require('@playwright/test')
async function main() {
  await esbuild.build({ entryPoints: [path.join(__dirname, 'ui-fixture.tsx')], bundle: true, outfile: path.join(__dirname, 'ui.js'), alias: { common: path.resolve('src/common') }, plugins: [{ name: 'scss', setup(build) { build.onLoad({ filter: /\.scss$/ }, async (args) => ({ contents: sass.compile(args.path, { logger: sass.Logger.silent }).css, loader: 'css' })) } }] })
  fs.writeFileSync(path.join(__dirname, 'ui.html'), '<!DOCTYPE html><html lang="pt-BR"><meta charset="utf-8"><link rel="stylesheet" href="ui.css"><style>html,body{margin:0;background:#0a0e14;color:#f0f4f8;font-family:Arial,sans-serif}button,input,select,textarea{font:inherit}*{box-sizing:border-box}</style><div id="root"></div><script src="ui.js"></script></html>')
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  let app
  try {
    app = await _electron.launch({ args: [path.join(__dirname, 'ui-main.cjs')], env })
    const page = await app.firstWindow()
    await page.route('https://**', (route) => route.abort())
    const errors = []; page.on('pageerror', (error) => errors.push(error.message))
    await expect(page.getByRole('button', { name: 'Editar capa de Matrix', exact: true })).toBeVisible()
    await expect(page.locator('.movie-poster-card')).toHaveCount(2)
    await expect(page.locator('.continue-section')).toHaveCount(0)
    await page.screenshot({ path: path.join(__dirname, 'library.png'), fullPage: true })
    await page.getByRole('button', { name: 'Buscar capas em português', exact: true }).click()
    expect(await page.evaluate(() => window.smoke.mode)).toBe('portuguese')
    await page.getByRole('button', { name: 'Editar capa de Matrix', exact: true }).click()
    const title = page.locator('.edit-fields-col .form-group input').first()
    await expect(title).toHaveValue('Matrix')
    await page.getByRole('button', { name: 'Identificar e buscar capas', exact: true }).click()
    await page.getByRole('button', { name: /The Matrix.*1999/ }).click()
    await expect(title).toHaveValue('Matrix')
    await expect(page.getByText(/Capa em português encontrada/)).toBeVisible()
    await expect(page.getByRole('button', { name: 'Escolher esta capa' })).toHaveCount(2)
    await page.getByRole('button', { name: 'Escolher esta capa' }).nth(1).click()
    await page.locator('.alazter-edit-modal').evaluate((element) => { element.scrollTop = 0 })
    await page.screenshot({ path: path.join(__dirname, 'editor.png') })
    await page.getByRole('button', { name: 'Salvar no Ghost', exact: true }).click()
    await expect(page.locator('.alazter-edit-modal')).toHaveCount(0)
    const saved = await page.evaluate(() => ({ ...window.smoke.saved[0], expected: window.smoke.altPoster }))
    expect(saved.movie.title).toBe('Matrix'); expect(saved.movie.coverUrl).toBe(saved.expected)
    expect(saved.movie.artworkLanguage).toBe('pt'); expect(saved.options.applyToShow).toBe(false)
    await page.getByRole('button', { name: 'Editar capa de Os Guardiões', exact: true }).click()
    await expect(page.locator('.alazter-edit-modal input[type="checkbox"]').first()).toBeChecked()
    await page.locator('.alazter-edit-modal .modal-close-btn').click()
    await page.locator('.header-nav-tabs').getByRole('button', { name: 'Configurações', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Capas e identificação das obras' })).toBeVisible()
    await page.locator('.alazter-metadata-settings input[type="password"]').fill('test-token-never-exposed')
    await page.getByRole('button', { name: 'Salvar preferências de capas', exact: true }).click()
    await expect(page.getByText('Preferências de capas salvas.')).toBeVisible()
    await expect(page.locator('.alazter-metadata-settings input[type="password"]')).toHaveValue('')
    await page.setViewportSize({ width: 1100, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    await page.screenshot({ path: path.join(__dirname, 'settings-1100.png'), fullPage: true })
    await page.evaluate(() => window.smoke.openDialog())
    const dialog = page.getByRole('dialog', { name: 'Configurações do Alazterflix' })
    await expect(dialog).toBeVisible()
    await dialog.getByRole('button', { name: 'Capas e metadados', exact: true }).click()
    await expect(dialog.getByRole('heading', { name: 'Capas e identificação das obras' })).toBeVisible()
    await dialog.getByRole('button', { name: 'Salvar preferências de capas', exact: true }).click()
    await expect(dialog.getByText('Preferências de capas salvas.')).toBeVisible()
    await page.screenshot({ path: path.join(__dirname, 'plugin-settings.png') })
    await dialog.getByRole('button', { name: 'Fechar configurações', exact: true }).click()
    await expect(dialog).toHaveCount(0)
    const nativeImage = await app.evaluate(() => global.smokeNativeImage)
    expect(nativeImage).toEqual({ valid: true, jpegMagic: 'ffd8ff' })
    expect(errors).toEqual([])
    fs.writeFileSync(path.join(__dirname, 'ui-result.json'), JSON.stringify({ passed: true, cardCount: 2, preservedTitle: saved.movie.title, portuguesePoster: saved.movie.artworkLanguage, episodicGrouping: true, settingsSaved: true, nativeImage, pageErrors: errors }, null, 2))
    console.log('Editor, seleção de capa portuguesa, nome preservado, agrupamento e preferências: OK')
  } finally { if (app) await app.close() }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
