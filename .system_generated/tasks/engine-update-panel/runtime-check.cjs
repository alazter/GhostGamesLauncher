const fs = require('node:fs')
const path = require('node:path')
const {spawn} = require('node:child_process')
const esbuild = require('esbuild')
const repository = path.resolve(__dirname, '../../..')
const entry = path.join(repository,'scripts/engines/runtime_smoke.ts')
const outfile = path.join(__dirname, 'runtime.cjs')
esbuild.buildSync({stdin:{contents:fs.readFileSync(entry,'utf8').replace("resolve('public/engine-bundles')",JSON.stringify(path.join(__dirname,'candidate-bundles'))),resolveDir:path.dirname(entry),loader:'ts'},bundle:true,platform:'node',external:['electron'],outfile,tsconfig:path.join(repository,'tsconfig.json')})
const child = spawn(require('electron'),[outfile],{windowsHide:true,stdio:'inherit'})
const timer = setTimeout(()=>{child.kill();process.exitCode=1},120000)
child.on('exit',code=>{clearTimeout(timer);process.exitCode=code||0})
child.on('error',error=>{clearTimeout(timer);console.error(error.message);process.exitCode=1})
