const path=require('node:path')
const {pathToFileURL}=require('node:url')
const {chromium,expect}=require('@playwright/test')
;(async()=>{
  const browser=await chromium.launch({channel:'msedge',headless:true})
  try {
    const page=await browser.newPage({viewport:{width:320,height:900},isMobile:true,hasTouch:true})
    await page.addInitScript(()=>localStorage.setItem('ghost_alazterflix_card_preferences',JSON.stringify({style:'clean',showTitle:true,titleAlignment:'right'})))
    await page.goto(pathToFileURL(path.join(__dirname,'ui.html')).href)
    const card=page.locator('.catalog-home .catalog-modern-card').first()
    await expect(card.locator('.catalog-clean-title')).toBeVisible()
    await card.locator('.catalog-modern-open').tap()
    const panel=card.locator('.catalog-hover-panel')
    await expect(panel).toBeVisible()
    const rating=panel.getByRole('textbox')
    await rating.fill('9,5')
    await panel.getByRole('button',{name:'Adicionar Agent Aika aos favoritos',exact:true}).tap()
    await expect(rating).toHaveValue('9.5')
    await panel.getByRole('button',{name:'Marcar Agent Aika como assistido',exact:true}).tap()
    await page.waitForTimeout(400)
    await expect(panel.getByRole('button',{name:'Desmarcar Agent Aika como assistido',exact:true})).toHaveAttribute('aria-pressed','true')
    expect(await panel.locator('.catalog-icon-action').first().evaluate(e=>e.getBoundingClientRect().width)).toBeGreaterThanOrEqual(44)
    await card.screenshot({path:path.join(__dirname,'touch-320.png')})
    console.log('PASS: actual touch cards at 320px; tap overlay; comma normalization; favorite and watched; 44px targets.')
  } finally {await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
