const fs=require('node:fs')
const path=require('node:path')
const esbuild=require('esbuild')
const sass=require('sass')
const { _electron, expect }=require('@playwright/test')
async function main(){
  await esbuild.build({entryPoints:[path.join(__dirname,'ui-fixture.tsx')],bundle:true,outfile:path.join(__dirname,'ui.js'),external:['/heroic_background.jpg'],loader:{'.png':'dataurl','.jpg':'dataurl','.svg':'dataurl','.woff2':'dataurl','.woff':'dataurl'},alias:{common:path.resolve('src/common'),frontend:path.resolve('src/frontend')},plugins:[{name:'scss',setup(build){build.onLoad({filter:/\.scss$/},async args=>({contents:sass.compile(args.path,{logger:sass.Logger.silent}).css,loader:'css'}))}}]})
  fs.writeFileSync(path.join(__dirname,'ui.html'),'<!doctype html><html lang="pt-BR"><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><link rel="stylesheet" href="ui.css"><style>html,body{margin:0;background:#090c12;color:#eef1f6;font-family:Arial,sans-serif}*{box-sizing:border-box}input{user-select:text}</style><div id="root"></div><script src="ui.js"></script></html>')
  const env={...process.env};delete env.ELECTRON_RUN_AS_NODE
  let app
  try {
    app=await _electron.launch({args:[path.join(__dirname,'ui-main.cjs')],env})
    const page=await app.firstWindow()
    const errors=[];page.on('pageerror',error=>errors.push(error.message))
    await page.route('https://**',route=>route.abort())
    await page.evaluate(()=>localStorage.clear())
    await page.reload()
    const settings=page.getByRole('button',{name:'Configurações',exact:true})
    const catalog=async()=>{
      const back=page.getByRole('button',{name:'Voltar ao catálogo',exact:true})
      if(await back.isVisible())await back.click()
      await page.getByRole('button',{name:/^Todos \(/}).click()
    }
    await expect(page.locator('.catalog-home .catalog-poster')).toHaveCount(2)
    await settings.click()
    await expect(page.getByRole('heading',{name:'Aparência dos cards',exact:true})).toBeVisible()
    const appearance=page.locator('.settings-view .catalog-card-settings')
    for(const name of ['Estilo atual · Selecionado','Informações abaixo','Capa limpa']) await expect(appearance.getByRole('button',{name,exact:true})).toBeVisible()
    await appearance.getByRole('button',{name:'Capa limpa',exact:true}).click()
    for(const alignment of ['left','center','right']) {
      await appearance.getByRole('combobox',{name:'Alinhamento do nome'}).selectOption(alignment)
      expect(await appearance.locator('.catalog-clean-title').evaluate(e=>getComputedStyle(e).textAlign)).toBe(alignment)
    }
    await appearance.getByRole('combobox',{name:'Alinhamento do nome'}).selectOption('left')
    await page.waitForTimeout(350)
    await appearance.screenshot({path:path.join(__dirname,'settings.png')})
    await catalog()
    const card=page.locator('.catalog-home .catalog-modern-card').filter({has:page.getByRole('heading',{name:'Agent Aika',exact:true})})
    await expect(card).toHaveCount(1)
    expect(await card.locator('.catalog-clean-title').evaluate(e=>getComputedStyle(e).backgroundColor)).toBe('rgba(0, 0, 0, 0)')
    expect(await card.locator('.catalog-clean-title').evaluate(e=>!e.closest('.catalog-modern-surface'))).toBe(true)
    await card.locator('.catalog-modern-open').hover()
    const rate=card.getByRole('textbox',{name:'Sua nota de 0 a 10 para Agent Aika'})
    await rate.fill('9,5');await rate.press('Enter');await expect(rate).toHaveValue('9.5')
    await expect.poll(()=>page.evaluate(()=>window.smoke.state().movies.filter(m=>m.isSeries).every(m=>m.userRating===9.5))).toBe(true)
    await rate.fill('11');await rate.press('Enter');await expect(card.getByRole('alert')).toBeVisible()
    expect(await page.evaluate(()=>window.smoke.state().movies[0].userRating)).toBe(9.5)
    await rate.fill('0');await rate.press('Enter')
    await expect.poll(()=>page.evaluate(()=>window.smoke.state().movies[0].userRating)).toBe(0)
    await rate.fill('9,5')
    const watched=card.getByRole('button',{name:'Marcar Agent Aika como assistido',exact:true})
    await watched.click()
    await expect(card.getByRole('button',{name:'Desmarcar Agent Aika como assistido',exact:true})).toHaveAttribute('aria-pressed','true')
    await expect(rate).toHaveValue('9.5')
    await card.getByRole('button',{name:'Adicionar Agent Aika aos favoritos',exact:true}).click()
    await expect(card.getByRole('button',{name:'Remover Agent Aika dos favoritos',exact:true})).toHaveAttribute('aria-pressed','true')
    await card.screenshot({path:path.join(__dirname,'clean-overlay.png')})
    await card.getByRole('button',{name:'Detalhes',exact:true}).click()
    await expect(page.getByText('Sua nota: 9.5/10',{exact:true})).toBeVisible()
    await page.locator('.alazter-show-modal .modal-close-btn').click()
    await settings.click()
    await appearance.getByRole('button',{name:'Informações abaixo',exact:true}).click()
    await catalog()
    const caption=page.locator('.catalog-home .catalog-modern-card--caption').first()
    await expect(caption.locator('.catalog-modern-caption')).toBeVisible()
    await caption.locator('.catalog-modern-open').focus();await page.keyboard.press('Tab')
    await expect(caption.getByRole('button',{name:/favoritos/})).toBeFocused()
    await caption.screenshot({path:path.join(__dirname,'caption-overlay.png')})
    const film=page.locator('.catalog-home .catalog-modern-card').filter({has:page.getByRole('heading',{name:'Filme de teste',exact:true})})
    await expect(film.locator('.catalog-modern-caption .catalog-modern-rating')).toHaveText(/—.*TMDB/)
    await settings.click();await appearance.getByRole('button',{name:'Capa limpa',exact:true}).click()
    await appearance.getByRole('checkbox',{name:'Mostrar nome abaixo da capa limpa'}).uncheck()
    await catalog()
    await expect(page.locator('.catalog-home .catalog-clean-title')).toHaveCount(0)
    for(const width of [1400,900,600,420,320]){
      await page.setViewportSize({width,height:1000})
      await page.locator('.catalog-home .catalog-modern-card').first().hover({position:{x:3,y:3}})
      await page.locator('.catalog-home .catalog-modern-open').first().focus()
      await page.waitForTimeout(350)
      expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true)
      const panel=page.locator('.catalog-home .catalog-hover-panel').first()
      for(const action of ['.catalog-icon-action','.catalog-card-play','.catalog-card-details']) {
        const button=panel.locator(action).first();await button.scrollIntoViewIfNeeded();await expect(button).toBeVisible()
      }
      await page.locator('.catalog-home .movies-grid').screenshot({path:path.join(__dirname,`grid-${width}.png`)})
    }
    await page.setViewportSize({width:1400,height:1000})
    await settings.click();await appearance.getByRole('checkbox',{name:'Mostrar nome abaixo da capa limpa'}).check()
    await page.evaluate(()=>window.smoke.openDialog())
    const dialog=page.getByRole('dialog',{name:'Configurações do Alazterflix'})
    await dialog.getByRole('button',{name:'Aparência dos cards',exact:true}).click()
    await dialog.getByRole('combobox',{name:'Alinhamento do nome'}).selectOption('center')
    expect(await appearance.getByRole('combobox',{name:'Alinhamento do nome'}).inputValue()).toBe('center')
    await dialog.getByRole('button',{name:'Fechar configurações'}).click()
    await page.reload();await catalog()
    expect(await page.locator('.catalog-home .catalog-clean-title').first().evaluate(e=>getComputedStyle(e).textAlign)).toBe('center')
    await page.locator('.catalog-home .catalog-modern-card').first().hover({position:{x:3,y:3}})
    await page.locator('.catalog-home .catalog-card-play').first().click()
    await expect.poll(()=>page.evaluate(()=>window.smoke.streams.length)).toBe(1)
    expect(errors).toEqual([])
    fs.writeFileSync(path.join(__dirname,'result.json'),JSON.stringify({passed:true,styles:3,alignment:3,decimal:true,watchedAndFavoritesIndependent:true,widths:[1400,900,600,420,320],pageErrors:errors},null,2))
    console.log('PASS: real catalog/settings, 3 styles, alignment, decimal rating, grouped watched, favorites, TMDB provenance, details/play, keyboard, reload and responsive layouts.')
  } finally {if(app)await app.close()}
}
main().catch(error=>{console.error(error);process.exitCode=1})
