const fs = require('fs')
const path = require('path')
const esbuild = require('esbuild')
const { _electron, expect } = require('@playwright/test')
async function main() {
  const alias = { common: path.resolve('src/common'), frontend: path.resolve('src/frontend') }
  await esbuild.build({ entryPoints: [path.join(__dirname, 'ui-fixture.tsx')], bundle: true, outfile: path.join(__dirname, 'ui.js'), alias })
  await esbuild.build({ entryPoints: ['src/backend/releases/drmSites.ts'], bundle: true, platform: 'node', external: ['electron'], outfile: path.join(__dirname, 'sites.cjs'), alias })
  fs.writeFileSync(path.join(__dirname, 'ui.html'), '<!DOCTYPE html><html lang="pt-BR"><meta charset="utf-8"><link rel="stylesheet" href="ui.css"><style>html,body,#root{margin:0;width:100%;height:100%;background:#0d0b22;color:#f4f2ff;font-family:Arial}button,input,select{font:inherit}*{box-sizing:border-box}</style><div id="root"></div><script src="ui.js"></script></html>')
  const env = { ...process.env }; delete env.ELECTRON_RUN_AS_NODE
  let app
  try {
    app = await _electron.launch({ args: [path.join(__dirname, 'ui-main.cjs')], env })
    const page = await app.firstWindow()
    const errors = []; page.on('pageerror', (error) => errors.push(error.message))
    const check = page.getByRole('button', { name: 'Verificar DRM de todos os jogos carregados e monitorados', exact: true })
    await expect(check).toBeEnabled()
    await expect(page.getByRole('button', { name: 'Liberar acesso ao HizSearch', exact: true })).toHaveCount(0)
    expect(await page.evaluate(() => window.smoke.calls.every(call => call.manual === undefined))).toBe(true)
    await expect(check).toHaveAttribute('title', /todos os 4 jogos/)
    const expand = page.getByRole('button', { name: 'Expandir calendário', exact: true })
    expect(await check.evaluate((element) => element.nextElementSibling?.getAttribute('aria-label'))).toBe('Expandir calendário')
    await check.click()
    await expect(page.getByRole('button', { name: 'Parar verificação de DRM' })).toBeVisible()
    await expect(page.getByText(/Verificação concluída: 4 de 4 jogos consultados/)).toBeVisible()
    const ids = await page.evaluate(() => window.smoke.calls.filter((call) => call.refresh).map((call) => call.id).sort())
    expect(ids).toEqual(['keep-driving', 'minecraft-dungeons-ii', 'monitored-only', 'persona-3-reload'])
    expect(await page.evaluate(() => window.smoke.calls.filter(call => call.refresh).every(call => call.manual === 'general'))).toBe(true)
    await expect(page.locator('.nr-drm-badge.nr-drm--cracked')).toHaveCount(3)
    await page.screenshot({ path: path.join(__dirname, 'header-1500.png') })
    for (const width of [1100, 900, 650]) {
      await page.setViewportSize({ width, height: 900 })
      const bounds = await check.boundingBox(); const other = await expand.boundingBox()
      expect(bounds.x + bounds.width).toBeLessThanOrEqual(width)
      expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    }
    await page.screenshot({ path: path.join(__dirname, 'header-650.png') })
    const unlock = page.getByRole('button', { name: 'Liberar acesso ao HizSearch', exact: true })
    await expect(unlock).toBeVisible()
    await unlock.click()
    await expect(page.getByText(/Consulta do HizSearch concluída: 4 de 4 jogos consultados/)).toBeVisible()
    await expect(unlock).toHaveCount(0)
    expect(await page.evaluate(() => window.smoke.calls.filter(call => call.manual === 'hiz').length)).toBe(4)
    const endings = await page.evaluate(() => { window.smoke.hizVerified = false; window.smoke.manualDelay = 500; return window.smoke.endCalls })
    await check.click()
    await expect(unlock).toBeVisible()
    await expect(page.getByRole('button', { name: 'Parar verificação de DRM' })).toBeVisible()
    await unlock.click()
    await expect(page.getByText(/Consulta do HizSearch concluída: 4 de 4 jogos consultados/)).toBeVisible()
    expect(await page.evaluate(() => window.smoke.endCalls)).toBe(endings + 1)
    expect(await page.evaluate(() => window.smoke.verifyCalls)).toBe(2)
    await page.setViewportSize({ width: 1500, height: 950 })
    await page.getByRole('button', { name: 'Detalhes de Minecraft Dungeons II', exact: true }).click()
    await expect(page.getByText(/Resultado salvo\. Consultas automáticas encerradas/)).toBeVisible()
    await expect(page.getByRole('button', { name: 'SkidrowReloaded', exact: true })).toBeVisible()
    await expect(page.getByRole('button', { name: 'AnkerGames', exact: true })).toBeVisible()
    await page.getByRole('button', { name: 'HizSearch', exact: true }).click()
    expect(await page.evaluate(() => window.smoke.opened)).toContain('https://hizsearch.pages.dev/')
    const before = await page.evaluate(() => window.smoke.calls.length)
    await page.getByRole('button', { name: 'Atualizar status do DRM', exact: true }).click()
    await expect(page.getByRole('button', { name: 'Atualizar status do DRM', exact: true })).toBeEnabled()
    expect(await page.evaluate(() => window.smoke.calls.length)).toBe(before + 1)
    expect(await page.evaluate(() => window.smoke.calls.at(-1).manual)).toBeUndefined()
    await page.screenshot({ path: path.join(__dirname, 'details.png') })
    expect(errors).toEqual([])
    fs.writeFileSync(path.join(__dirname, 'ui-result.json'), JSON.stringify({ passed: true, checked: ids, headerPosition: 'beside-calendar-expand', responsiveWidths: [1500, 1100, 900, 650], manualIndividual: true, sourcesShown: 3, errors }, null, 2))
    console.log('Cabeçalho, consulta geral, quatro jogos únicos, fontes, consulta individual e larguras: OK')
  } finally { if (app) await app.close() }
}
main().catch((error) => { console.error(error); process.exitCode = 1 })
